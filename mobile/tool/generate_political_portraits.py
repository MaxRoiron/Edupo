#!/usr/bin/env python3
"""Validate the reviewed Commons portrait manifest and generate Dart metadata.

Portrait image files are reviewed/downloaded separately. This script never
fetches media or changes pixels; it keeps the in-app attribution in sync.
"""

import json
import subprocess
from pathlib import Path
from urllib.parse import urlparse

ROOT = Path(__file__).resolve().parents[2]
CATALOG = ROOT / 'mobile/assets/data/political_parties_2027.json'
MANIFEST = ROOT / 'docs/research/presidentielle-2027/portraits.json'
OUTPUT = ROOT / 'mobile/lib/models/political_portraits.dart'


def dart_string(value):
    return json.dumps(value, ensure_ascii=False).replace('$', r'\$')


def build():
    catalog = json.loads(CATALOG.read_text())
    manifest = json.loads(MANIFEST.read_text())
    names = {
        person['name']
        for party in catalog['parties']
        for person in [*party['leadership'], *party['election2027']['people']]
    }
    portraits = manifest['portraits']
    unavailable = set(manifest['unavailable'])
    covered = {portrait['name'] for portrait in portraits}
    assert len(covered) == len(portraits), 'Duplicate portrait names'
    assert covered.isdisjoint(unavailable)
    assert names == covered | unavailable, f'Unreviewed people: {names - covered - unavailable}'
    for portrait in portraits:
        assert (ROOT / 'mobile' / portrait['asset']).is_file(), portrait
        assert portrait['author'] and portrait['license'], portrait
        assert urlparse(portrait['sourceUrl']).netloc == 'commons.wikimedia.org', portrait
        if portrait['license'] != 'Public domain':
            assert portrait['licenseUrl'].startswith('https://'), portrait

    lines = [
        '// Generated by tool/generate_political_portraits.py from the reviewed',
        '// research portrait manifest. Do not edit the credits here by hand.',
        'class PoliticalPortrait {',
        '  const PoliticalPortrait({',
        '    required this.asset,',
        '    required this.author,',
        '    required this.license,',
        '    required this.licenseUrl,',
        '    required this.sourceUrl,',
        '  });',
        '  final String asset, author, license, licenseUrl, sourceUrl;',
        '}',
        '',
        'const politicalPortraits = <String, PoliticalPortrait>{',
    ]
    for p in portraits:
        lines.extend([
            f'  {dart_string(p["name"])}: PoliticalPortrait(',
            f'    asset: {dart_string(p["asset"])},',
            f'    author: {dart_string(p["author"])},',
            f'    license: {dart_string(p["license"])},',
            f'    licenseUrl: {dart_string(p["licenseUrl"])},',
            f'    sourceUrl: {dart_string(p["sourceUrl"])},',
            '  ),',
        ])
    lines.append('};')
    OUTPUT.write_text('\n'.join(lines) + '\n')
    subprocess.run(['dart', 'format', str(OUTPUT)], check=True, capture_output=True)
    print(f'{len(covered)} portraits, {len(unavailable)} portrait unavailable')


if __name__ == '__main__':
    build()
